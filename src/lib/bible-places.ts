export function placeById(id: string): BiblePlace | undefined {
  return BIBLE_PLACES.find((p) => p.id === id);
}

function key(book: string, chapter: number) {
  return `${book}:${chapter}`;
}

/** Um local está descoberto se for `core` ou se o usuário leu um dos capítulos ligados a ele. */
export function isPlaceDiscovered(place: BiblePlace, readSet: Set<string>): boolean {
  if (place.core) return true;
  return (place.discoverBy ?? []).some((d) => readSet.has(key(d.book, d.chapter)));
}

/** Só conta os locais que exigem leitura — os `core` não são "conquista". */
export function countDiscoveredPlaces(readSet: Set<string>): number {
  return BIBLE_PLACES.filter((p) => !p.core && isPlaceDiscovered(p, readSet)).length;
}

export function unlockableePlacesTotal(): number {
  return BIBLE_PLACES.filter((p) => !p.core).length;
}

