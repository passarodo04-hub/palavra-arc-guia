export const MAP_BOUNDS = { minLng: 10, maxLng: 48, minLat: 26, maxLat: 43 };

export function projectPlace(coords: { lat: number; lng: number }): { x: number; y: number } {
  const { minLng, maxLng, minLat, maxLat } = MAP_BOUNDS;
  const x = ((coords.lng - minLng) / (maxLng - minLng)) * 1000;
  const y = ((maxLat - coords.lat) / (maxLat - minLat)) * 640;
  return { x, y };
}